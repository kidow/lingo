import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {createHash} from 'node:crypto'
import {compileProgressive,sourceGroups,sourceRoot,sourceProofFile,sourceWholeFileSHA256} from './progressive.mjs'
import {HANJA_STROKES,hanjaStrokeData} from '../../lib/hanja-strokes.ts'

const read = file => readFileSync(new URL(file, import.meta.url))
const object = file => JSON.parse(read(file))
const hash = value => createHash('sha256').update(value).digest('hex')
const audit = object('native-server-source-audit.json')
const review = object('review.json')
const source = object('sources.json')
const metadata = object('metadata.json')
assert.equal(hash(read('native-server-source-audit.json')), review.originalSourceManifestSHA256)
for (const [file,pin] of Object.entries({...audit.inputSHA256,...review.additionalOriginalBytePins})) assert.equal(hash(read(file)), pin, 'Immutable original input ' + file)
assert.equal(sourceRoot, 'u81b5-ue0103')
assert.equal(sourceRoot, audit.selectedWhole)
assert.equal(sourceProofFile, audit.selectedProof)
assert.equal(hash(read(sourceProofFile)), sourceWholeFileSHA256)
const header = object('engine-proof.json')
const selected = object(sourceProofFile)
const proof = {engineRevision:header.engineRevision,engineHashes:header.engineHashes,...selected}
const before = JSON.stringify(proof)
assert.deepEqual(Object.keys(proof).sort(), ['defaults','engineHashes','engineRevision','groups','trace'])
assert.equal(hash(before), '121d82e467a255da0d536f04c6481ea5d24f62d647fe32be4bb56f4757b72670')
const compiled = compileProgressive(proof.trace, proof)
assert.equal(JSON.stringify(proof), before)
assert.equal(hash(JSON.stringify(compiled)), review.compiledSHA256)
assert.equal(compiled.length, 16)
assert.equal(compiled.flat().length, 17)
assert.equal(compiled.flat().flatMap(mask => mask.outline.match(/M[^Z]+Z/g) || []).length, 37)
const entry = hanjaStrokeData({glyph:'膵',strokes:16})
assert(entry)
assert.equal(HANJA_STROKES.filter(item => item.glyph === '膵').length, 1)
assert.equal(entry.verifiedAt, '2026-10-17')
assert.deepEqual(entry.outlines, compiled)
assert.deepEqual(entry.paths, compiled.map(pen => pen.map(mask => mask.outline).join(' ')))
assert.equal(entry.pathsSha256, hash(JSON.stringify(entry.paths)))
assert.deepEqual(entry.sourceStrokeIndices, sourceGroups.map(group => group[0] + 1))
assert.deepEqual(sourceGroups, review.sourceGroupsZeroBased)
const geometryBytes = read('../../public/hanja-strokes/glyphwiki/u81b5.json')
const geometry = JSON.parse(geometryBytes)
assert.equal(entry.geometrySource, hash(geometryBytes))
assert.equal(geometry.root, sourceRoot)
assert.deepEqual(geometry.records, source.records)
assert.deepEqual(geometry.drawTrace, proof.trace)
assert.deepEqual(geometry.engineHashes, proof.engineHashes)
assert.deepEqual(geometry.enginePreset, proof.defaults)
assert.deepEqual(geometry.sourceGroups, sourceGroups)
for (const key of ['orderReviewSha256','geometryReviewSha256','directionReviewSha256']) assert.equal(entry.sourceReference[key], hash(read('review.json')))
assert.equal(entry.sourceReference.dictionarySvgSha256, metadata.dictionary.sha256)
assert.equal(review.wholeVariantsReviewed, 8)
assert.deepEqual(review.compatibleWholeRoots, ['u81b5-ue0103'])
assert.equal(review.wholeVariants.filter(variant => variant.selected && variant.compatible).length, 1)
assert.equal(review.wholeVariants.filter(variant => !variant.selected && !variant.compatible).length, 7)
assert.equal(review.progressiveFramesApproved, 144)
assert.equal(review.progressiveFramesReviewed, 144)
assert.deepEqual(review.progressivePensReviewed, Array.from({length:16},(_,i) => i + 1))
assert.deepEqual(review.dictionaryDirectionStrokes, review.progressivePensReviewed)
assert.deepEqual(review.curveFineChecks.map(check => check.pen), audit.finePens)
assert(review.curveFineChecks.every(check => check.passed && check.noCompletionPop && check.size === 520 && check.beforePercent === 99.99 && check.afterPercent === 100))
const boundary = review.maskBoundaryObservations[0]
assert(boundary.nativeReviewed && boundary.before && boundary.at && boundary.after && boundary.connectedReveal && boundary.passed)
assert.equal(boundary.start, 0.9251959408175717)
assert.equal(boundary.additionalProbePercent, 97)
assert.equal(review.actualReplayProgress[0].observedPercent, 3.6925)
assert.equal(review.actualReplayProgress[0].completedAX, 100)
assert(review.actualReplayProgress[0].completedScreenshot && review.actualReplayProgress[0].passed)
assert(review.nativeApproval && review.runtimeApplied && review.allStrokesReviewed)
assert.equal(review.compilerFileSHA256, hash(read('progressive.mjs')))
assert.equal(metadata.runtimeApplied, false)
assert.equal(audit.nativeApproval, false)
assert.equal(review.appUIAutoplayVerifiedThisBatch, false)
const notice = read('../../public/hanja-strokes/glyphwiki/NOTICE-u81b5.md').toString()
assert(notice.includes(entry.geometryLicense.revision))
assert(notice.includes(entry.geometryLicense.modifications))
console.log(JSON.stringify({glyph:'膵',pens:16,masks:17,polygons:37,frames:144,selectedWhole:sourceRoot,unselectedWholeVariants:7,sourcePreserved:true,runtimeApplied:true,appUIAutoplayVerifiedThisBatch:false}))
