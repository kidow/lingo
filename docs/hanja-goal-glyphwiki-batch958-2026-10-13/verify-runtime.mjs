import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {createHash} from 'node:crypto'
import {compileSourceWhole,sourceGroups,sourceOrderPermutation,wholeSourceIdentities} from './progressive-order-candidate.mjs'
import {HANJA_STROKES,hanjaStrokeData} from '../../lib/hanja-strokes.ts'

const read = file => readFileSync(new URL(file,import.meta.url))
const object = file => JSON.parse(read(file))
const hash = value => createHash('sha256').update(value).digest('hex')
const preparation = object('source-order-combined-preparation.json')
const review = object('review.json')
assert.equal(hash(read('source-order-combined-preparation.json')),review.immutablePreparationSHA256)
for (const [file,pin] of Object.entries({...preparation.originalInputBytePins,...preparation.newFileSHA256})) assert.equal(hash(read(file)),pin,'Immutable original/candidate ' + file)
const root = 'u8600-ue0102'
const identity = wholeSourceIdentities[root]
assert.deepEqual(identity,preparation.identity)
assert.deepEqual(Object.keys(identity).sort(),['file','fileSHA256','root'])
const header = object('engine-proof.json')
const selected = object(identity.file)
const proof = {engineRevision:header.engineRevision,engineHashes:header.engineHashes,...selected,sourceRoot:root,sourceProofFile:identity.file,sourceProofFileSHA256:identity.fileSHA256}
assert.deepEqual(Object.keys(proof).sort(),['defaults','engineHashes','engineRevision','groups','sourceProofFile','sourceProofFileSHA256','sourceRoot','trace'])
assert.equal(hash(JSON.stringify(proof)),preparation.fullProofSHA256)
const before = JSON.stringify(proof)
const strokes = compileSourceWhole(root,proof.trace,proof,identity)
assert.equal(JSON.stringify(proof),before)
assert.equal(hash(JSON.stringify(strokes)),review.compiledSHA256)
assert.equal(strokes.length,20)
assert.equal(strokes.flat().length,21)
assert.equal(strokes.flat().flatMap(mask => mask.outline.match(/M[^Z]+Z/g) || []).length,41)
const entry = hanjaStrokeData({glyph:'蘀',strokes:20})
assert(entry)
assert.equal(HANJA_STROKES.filter(item => item.glyph === '蘀').length,1)
assert.equal(entry.verifiedAt,'2026-10-17')
assert.deepEqual(entry.outlines,strokes)
assert.deepEqual(entry.paths,strokes.map(pen => pen.map(mask => mask.outline).join(' ')))
assert.equal(entry.pathsSha256,hash(JSON.stringify(entry.paths)))
assert.deepEqual(entry.sourceStrokeIndices,sourceGroups.map(group => group[0] + 1))
assert.deepEqual(sourceGroups,review.sourceGroupsZeroBased)
assert.deepEqual(sourceOrderPermutation,review.sourceOrderPermutation)
const geometryBytes = read('../../public/hanja-strokes/glyphwiki/u8600.json')
const geometry = JSON.parse(geometryBytes)
assert.equal(entry.geometrySource,hash(geometryBytes))
assert.equal(geometry.root,root)
assert.deepEqual(geometry.records,object('sources.json').records)
assert.deepEqual(geometry.drawTrace,proof.trace)
assert.deepEqual(geometry.engineHashes,proof.engineHashes)
assert.deepEqual(geometry.enginePreset,proof.defaults)
assert.deepEqual(geometry.sourceGroups,sourceGroups)
for (const field of ['orderReviewSha256','geometryReviewSha256','directionReviewSha256']) assert.equal(entry.sourceReference[field],hash(read('review.json')))
assert.equal(entry.sourceReference.dictionarySvgSha256,object('metadata.json').dictionary.sha256)
assert.equal(review.wholeVariantsReviewed,2)
assert.equal(review.wholeProofsReused,2)
assert.equal(review.wholeVariants.filter(whole => whole.observed).length,2)
assert.deepEqual(review.compatibleWholeRoots,[root])
assert.equal(review.progressiveFramesReviewed,180)
assert.equal(review.progressiveFramesApproved,180)
assert.equal(review.observationProvenance.originalProfileReused.coarseFrames + review.observationProvenance.correctedProfileObserved.coarseFrames,180)
assert.deepEqual(review.dictionaryDirectionStrokes,Array.from({length:20},(_,i) => i + 1))
assert.deepEqual(review.curveFineChecks.map(check => check.pen),[1,6,7,9,16,17])
assert(review.curveFineChecks.every(check => check.size === 520 && check.beforePercent === 99.99 && check.afterPercent === 100 && check.passed && check.noCompletionPop))
const boundary = review.maskBoundaryObservations[0]
assert(boundary.nativeReviewed && boundary.before && boundary.at && boundary.after && boundary.connectedReveal && boundary.passed)
assert.equal(boundary.start,0.9046270435086523)
assert.equal(boundary.additionalProbePercent,95)
assert.equal(review.actualReplayProgress[0].observedPercent,2.575)
assert.equal(review.actualReplayProgress[0].completedAX,100)
assert(review.actualReplayProgress[0].completedScreenshot && review.actualReplayProgress[0].passed)
assert(review.nativeApproval && review.runtimeApplied && review.allStrokesReviewed)
assert.equal(preparation.nativeApproval,false)
assert.equal(preparation.runtimeApplied,false)
assert.equal(object('metadata.json').runtimeApplied,false)
assert.equal(review.appUIAutoplayVerifiedThisBatch,false)
const notice = read('../../public/hanja-strokes/glyphwiki/NOTICE-u8600.md').toString()
assert(notice.includes(entry.geometryLicense.revision) && notice.includes(entry.geometryLicense.modifications))
console.log(JSON.stringify({glyph:'蘀',pens:20,masks:21,polygons:41,frames:180,sourceRoot:root,sourcePreserved:true,runtimeApplied:true,appUIAutoplayVerifiedThisBatch:false}))
