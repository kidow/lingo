import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {createHash} from 'node:crypto'
import {compileProgressive,sourceGroups,sourceRoot,selectedProofIdentity,sourceOrderPermutation} from './progressive-order-candidate.mjs'
import {HANJA_STROKES,hanjaStrokeData} from '../../lib/hanja-strokes.ts'

const read = file => readFileSync(new URL(file,import.meta.url))
const object = file => JSON.parse(read(file))
const hash = value => createHash('sha256').update(value).digest('hex')
const preparation = object('source-order-candidate-validation.json')
const review = object('review.json')
for (const [file,pin] of Object.entries({...preparation.originalBytePins,...preparation.newFileSHA256})) assert.equal(hash(read(file)),pin,'Pinned source ' + file)
assert.deepEqual(selectedProofIdentity,preparation.identityContract.selectedIdentity)
assert.deepEqual(Object.keys(selectedProofIdentity).sort(),['sourceRoot','sourceProofFile','sourceProofFileSha256','sourceHeaderFile','sourceHeaderFileSha256'].sort())
const header = object(selectedProofIdentity.sourceHeaderFile)
const selected = object(selectedProofIdentity.sourceProofFile)
const proof = {engineRevision:header.engineRevision,engineHashes:header.engineHashes,...selected}
const before = JSON.stringify(proof)
assert.deepEqual(Object.keys(proof).sort(),['defaults','engineHashes','engineRevision','groups','trace'])
assert.equal(hash(before),preparation.identityContract.fullSelectedProofSHA256)
const compiled = compileProgressive(proof.trace,proof,selectedProofIdentity)
assert.equal(JSON.stringify(proof),before)
assert.equal(hash(JSON.stringify(compiled)),review.compiledSHA256)
assert.equal(compiled.length,17)
assert.equal(compiled.flat().length,18)
assert.equal(compiled.flat().flatMap(mask => mask.outline.match(/M[^Z]+Z/g) || []).length,37)
const entry = hanjaStrokeData({glyph:'駸',strokes:17})
assert(entry)
assert.equal(HANJA_STROKES.filter(item => item.glyph === '駸').length,1)
assert.equal(entry.verifiedAt,'2026-10-17')
assert.deepEqual(entry.outlines,compiled)
assert.deepEqual(entry.paths,compiled.map(pen => pen.map(mask => mask.outline).join(' ')))
assert.equal(entry.pathsSha256,hash(JSON.stringify(entry.paths)))
assert.deepEqual(entry.sourceStrokeIndices,sourceGroups.map(group => group[0] + 1))
assert.deepEqual(sourceGroups,review.sourceGroupsZeroBased)
assert.deepEqual(sourceOrderPermutation,review.sourceOrderPermutation)
const geometryBytes = read('../../public/hanja-strokes/glyphwiki/u99f8.json')
const geometry = JSON.parse(geometryBytes)
const source = object('sources.json')
assert.equal(entry.geometrySource,hash(geometryBytes))
assert.equal(geometry.root,sourceRoot)
assert.deepEqual(geometry.records,source.records)
assert.deepEqual(geometry.drawTrace,proof.trace)
assert.deepEqual(geometry.engineHashes,proof.engineHashes)
assert.deepEqual(geometry.enginePreset,proof.defaults)
assert.deepEqual(geometry.sourceGroups,sourceGroups)
for (const field of ['orderReviewSha256','geometryReviewSha256','directionReviewSha256']) assert.equal(entry.sourceReference[field],hash(read('review.json')))
assert.equal(entry.sourceReference.dictionarySvgSha256,object('metadata.json').dictionary.sha256)
assert.equal(review.progressiveFramesReviewed,153)
assert.equal(review.progressiveFramesApproved,153)
assert.equal(review.observationProvenance.originalProfileReused.coarseFrames + review.observationProvenance.correctedProfileObserved.coarseFrames,153)
assert.deepEqual(review.dictionaryDirectionStrokes,Array.from({length:17},(_,i) => i + 1))
assert.deepEqual(review.curveFineChecks.map(check => check.pen),[1,6,7,8,9,10,11,14,15,16,17])
assert(review.curveFineChecks.every(check => check.size === 520 && check.beforePercent === 99.99 && check.afterPercent === 100 && check.passed && check.noCompletionPop))
const boundary = review.maskBoundaryObservations[0]
assert(boundary.nativeReviewed && boundary.before && boundary.at && boundary.after && boundary.connectedReveal && boundary.passed)
assert.equal(boundary.additionalProbePercent,95)
assert.equal(boundary.start,0.8934497274304181)
assert.equal(review.actualReplayProgress[0].observedPercent,2.9662)
assert.equal(review.actualReplayProgress[0].completedAX,100)
assert(review.actualReplayProgress[0].completedScreenshot && review.actualReplayProgress[0].passed)
assert(review.nativeApproval && review.runtimeApplied && review.allStrokesReviewed)
assert.equal(review.compilerFileSHA256,hash(read('progressive-order-candidate.mjs')))
assert.equal(object('metadata.json').runtimeApplied,false)
assert.equal(preparation.nativeApproval,false)
assert.equal(preparation.runtimeApplied,false)
assert.equal(review.appUIAutoplayVerifiedThisBatch,false)
const notice = read('../../public/hanja-strokes/glyphwiki/NOTICE-u99f8.md').toString()
assert(notice.includes(entry.geometryLicense.revision) && notice.includes(entry.geometryLicense.modifications))
console.log(JSON.stringify({glyph:'駸',pens:17,masks:18,polygons:37,frames:153,sourcePreserved:true,runtimeApplied:true,appUIAutoplayVerifiedThisBatch:false}))
