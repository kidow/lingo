import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {createHash} from 'node:crypto'
import {buildSourceProof, compileProgressive, sourceGroups, selectedProofIdentity, domesticToOriginalPen} from './domestic-order-adapter.mjs'
import {HANJA_STROKES, hanjaStrokeData} from '../../lib/hanja-strokes.ts'

const read = file => readFileSync(new URL(file, import.meta.url))
const object = file => JSON.parse(read(file))
const hash = value => createHash('sha256').update(value).digest('hex')
const audit = object('domestic-order-source-audit.json')
const review = object('review.json')
const source = object('sources.json')
const metadata = object('metadata.json')
for (const [file, pin] of Object.entries(audit.originalInputsBytePins)) assert.equal(hash(read(file)), pin, 'Immutable original input ' + file)
assert.equal(hash(read('domestic-order-adapter.mjs')), audit.adapterSHA256)
assert.deepEqual(Object.keys(selectedProofIdentity).sort(), ['root','sourceProofFile','sourceProofFileSHA256','engineHeaderSHA256','sourceFileSHA256','compilerFileSHA256'].sort())
assert.deepEqual(selectedProofIdentity, audit.caller.identity)
const proof = buildSourceProof(selectedProofIdentity)
const before = JSON.stringify(proof)
assert.deepEqual(Object.keys(proof).sort(), ['defaults','engineHashes','engineRevision','groups','trace'])
assert.equal(hash(before), audit.caller.fullProofSHA256)
const compiled = compileProgressive(proof.trace, proof, selectedProofIdentity)
assert.equal(JSON.stringify(proof), before)
assert.equal(hash(JSON.stringify(compiled)), audit.compiledSHA256)
assert.deepEqual(compiled.map(pen => hash(JSON.stringify(pen))), audit.permutedPerPenSHA256)
assert.equal(compiled.length, 15)
assert.equal(compiled.flat().length, 16)
assert.equal(compiled.flatMap(pen => pen.flatMap(mask => mask.outline.match(/M[^Z]+Z/g) || [])).length, 34)
const entry = hanjaStrokeData({glyph:'踧', strokes:15})
assert(entry)
assert.equal(HANJA_STROKES.filter(item => item.glyph === '踧').length, 1)
assert.equal(entry.verifiedAt, '2026-10-17')
assert.deepEqual(entry.outlines, compiled)
assert.deepEqual(entry.paths, compiled.map(pen => pen.map(mask => mask.outline).join(' ')))
assert.equal(entry.pathsSha256, hash(JSON.stringify(entry.paths)))
assert.deepEqual(entry.sourceStrokeIndices, sourceGroups.map(group => group[0] + 1))
assert.deepEqual(sourceGroups, review.sourceGroupsZeroBased)
assert.deepEqual(domesticToOriginalPen, review.domesticToOriginalPen)
const geometryBytes = read('../../public/hanja-strokes/glyphwiki/u8e27.json')
const geometry = JSON.parse(geometryBytes)
assert.equal(entry.geometrySource, hash(geometryBytes))
assert.equal(geometry.root, 'u8e27')
assert.deepEqual(geometry.records, source.records)
assert.deepEqual(geometry.drawTrace, proof.trace)
assert.deepEqual(geometry.engineHashes, proof.engineHashes)
assert.deepEqual(geometry.enginePreset, proof.defaults)
assert.deepEqual(geometry.sourceGroups, sourceGroups)
for (const key of ['orderReviewSha256','geometryReviewSha256','directionReviewSha256']) assert.equal(entry.sourceReference[key], hash(read('review.json')))
assert.equal(entry.sourceReference.dictionarySvgSha256, metadata.dictionary.sha256)
assert.equal(review.progressiveFramesApproved, 135)
assert.equal(review.progressiveFramesReviewed, 135)
assert.deepEqual(review.progressivePensReviewed, Array.from({length:15}, (_, i) => i + 1))
assert.deepEqual(review.dictionaryDirectionStrokes, review.progressivePensReviewed)
assert.deepEqual(review.curveFineChecks.map(check => check.pen), audit.finePens)
assert(review.curveFineChecks.every(check => check.passed && check.noCompletionPop && check.size === 520 && check.beforePercent === 99.99 && check.afterPercent === 100))
assert.equal(review.observationProvenance.priorRootObservationReused.coarseFrames, 117)
assert.equal(review.observationProvenance.currentRootObservation.coarseFrames, 18)
assert.deepEqual(review.observationProvenance.currentRootObservation.directions, [12,13])
assert.deepEqual(review.observationProvenance.currentRootObservation.finePens, [12,13,15])
assert(review.maskBoundaryObservations[0].passed && review.maskBoundaryObservations[0].nativeReviewed && review.maskBoundaryObservations[0].connectedReveal)
assert.equal(review.maskBoundaryObservations[0].additionalProbePercent, 90)
assert.equal(review.actualReplayProgress[0].observedPercent, 8.255)
assert.equal(review.actualReplayProgress[0].completedAX, 100)
assert(review.actualReplayProgress[0].passed)
assert.equal(review.compilerFileSHA256, hash(read('domestic-order-adapter.mjs')))
assert.equal(review.compiledSHA256, audit.compiledSHA256)
assert(review.nativeApproval && review.runtimeApplied && review.allStrokesReviewed)
assert.equal(review.appUIAutoplayVerifiedThisBatch, false)
assert.equal(metadata.runtimeApplied, false)
assert.equal(audit.nativeApproval, false)
assert.equal(audit.runtimeChanged, false)
const notice = read('../../public/hanja-strokes/glyphwiki/NOTICE-u8e27.md').toString()
assert(notice.includes(entry.geometryLicense.revision))
assert(notice.includes(entry.geometryLicense.modifications))
console.log(JSON.stringify({glyph:'踧', pens:15, masks:16, polygons:34, frames:135, sourcePreserved:true, runtimeApplied:true, appUIAutoplayVerifiedThisBatch:false}))
